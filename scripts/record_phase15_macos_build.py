"""Record an already built isolated native backend. Never downloads or builds.

Source releases must have been separately obtained and verified. This script
preserves the old Linux pins and writes only the new macOS validation manifest.
"""
from pathlib import Path
import hashlib
import json
import platform
import subprocess
import sys
import sysconfig

ROOT=Path(__file__).resolve().parents[1]
BUILD=ROOT/'results/runs/phase15_macos_build'
PYNAUTY_SHA='454d3b0e605d649d13478afb090daef4a152f15c4a337a391fe69fded7e683f2'
NAUTY_SHA='159d2156810a6bb240410cd61eb641add85088d9f15c888cdaa37b8681f929ce'


def sha(path):return hashlib.sha256(path.read_bytes()).hexdigest()


def main():
    if sys.platform!='darwin' or platform.machine()!='arm64':raise ValueError('macOS ARM64 required')
    if sha(BUILD/'pynauty-2.8.8.1.tar.gz')!=PYNAUTY_SHA or sha(BUILD/'nauty2_8_8.tar.gz')!=NAUTY_SHA:
        raise ValueError('Source release digest mismatch')
    metadata=json.loads((BUILD/'pypi-release.json').read_text())
    release=next(r for r in metadata['urls'] if r['packagetype']=='sdist')
    if release['digests']['sha256']!=PYNAUTY_SHA:raise ValueError('PyPI published digest mismatch')
    package=next((BUILD/'native-build').glob('lib.*/pynauty'))
    artifacts={p.relative_to(ROOT).as_posix():sha(p) for p in sorted(package.rglob('*')) if p.is_file() and p.suffix in ('.py','.so')}
    for name in ('phase15_nauty_macos.py','phase15_nauty_macos_worker.py','phase15_topology.py','phase15_nauty.py'):
        path=ROOT/'src/spatial_memory'/name;artifacts[path.relative_to(ROOT).as_posix()]=sha(path)
    pin=dict(profile='macos-arm64-compatibility-only',validation_only=True,production_enabled=False,
        namespace='phase1.5-macos-C3-COMPATIBILITY-CANDIDATE',target_namespace='phase1.5-v0.3-CANON-1',
        package_root=package.parent.relative_to(ROOT).as_posix(),artifact_sha256=artifacts,
        pynauty_version='2.8.8.1',nauty_version='nauty2_8_8',hard_memory_enforcement='BLOCKED',limit_bytes=536870912)
    source=BUILD/'pynauty-2.8.8.1/src';official=BUILD/'upstream-nauty/nauty2_8_8'
    comparison={}
    for p in sorted((source/'nauty2_8_8').iterdir()):
        # nauty.h is generated by configure for the target ABI; pin it separately.
        if p.name!='nauty.h' and p.suffix in ('.c','.h','.in') and (official/p.name).is_file():
            if p.read_bytes()!=(official/p.name).read_bytes():raise ValueError('Upstream source differs: '+p.name)
            comparison[p.name]=sha(p)
    old=json.loads((ROOT/'configs/phase15_nauty_backend.json').read_text())
    wrapper={}
    for name in ('nautywrap.c','nautywrap.h','graph.py','__init__.py'):
        p=source/'pynauty'/name;expected=old['dependency_sha256']['results/runs/phase1_5b01_dependencies/pynauty/'+name]
        if sha(p)!=expected:raise ValueError('Approved wrapper source changed')
        wrapper[name]=expected
    manifest=dict(python=sys.version,python_executable=sys.executable,abi=sysconfig.get_config_var('SOABI'),
        platform=platform.platform(),machine=platform.machine(),macos=subprocess.check_output(['sw_vers'],text=True),
        compiler=subprocess.check_output(['/usr/bin/clang','--version'],text=True),
        sdk=subprocess.check_output(['xcrun','--show-sdk-path'],text=True).strip(),
        sdk_version=subprocess.check_output(['xcrun','--show-sdk-version'],text=True).strip(),
        python_build_flags={k:sysconfig.get_config_var(k) for k in ('CC','CFLAGS','LDFLAGS','CONFIG_ARGS','MACOSX_DEPLOYMENT_TARGET')},
        build_environment=dict(CC='/usr/bin/clang',ARCHFLAGS='-arch arm64',PYTHONDONTWRITEBYTECODE='1'),
        build_command='isolated-venv/bin/python setup.py build --build-base ../native-build',
        build_tools=dict(setuptools='75.8.0',wheel='0.45.1'),
        sources=[dict(url=release['url'],sha256=PYNAUTY_SHA,published_pypi_digest_verified=True),
                 dict(url='https://pallini.di.uniroma1.it/nauty2_8_8.tar.gz',sha256=NAUTY_SHA,
                      provenance='upstream HTTPS plus bundled C/header/template comparison; no upstream signature claimed')],
        upstream_matching_files=comparison,approved_wrapper_sha256=wrapper,
        generated_nauty_header_sha256=sha(source/'nauty2_8_8/nauty.h'),
        generated_config_log_sha256=sha(source/'nauty2_8_8/config.log'),
        build_log_path='results/runs/phase15_macos_build/build.log',build_log_sha256=sha(BUILD/'build.log'),
        artifact_sha256=artifacts,
        native_file_info=subprocess.check_output(['file',str(next(package.glob('*.so')))],text=True).strip(),
        linked_libraries=subprocess.check_output(['otool','-L',str(next(package.glob('*.so')))],text=True),
        production_authorized=False)
    pin_path=ROOT/'configs/phase15_nauty_macos_validation.json'
    pin_path.write_text(json.dumps(pin,indent=2,sort_keys=True)+'\n')
    manifest['validation_pin_sha256']=sha(pin_path)
    output=ROOT/'results/phase1_5_bprime_macos/build_manifest.json'
    output.parent.mkdir(parents=True,exist_ok=True)
    output.write_text(json.dumps(manifest,sort_keys=True,indent=2)+'\n')
    print(json.dumps(dict(native=manifest['native_file_info'],native_sha256=sha(next(package.glob('*.so'))),source_matches=len(comparison))))


if __name__=='__main__':main()
